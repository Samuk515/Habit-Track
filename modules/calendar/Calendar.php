<?php
declare(strict_types=1);
require __DIR__ . '/../../includes/auth.php';
requireLogin();
require __DIR__ . '/../../includes/db.php';

$userId = (int) $_SESSION['user_id'];
$perPage = 15;
$page = isset($_GET['page']) ? max(1, (int) $_GET['page']) : 1;
$offset = ($page - 1) * $perPage;

$countStmt = mysqli_prepare($conn, 'SELECT COUNT(*) FROM CALENDAR_EVENT
    INNER JOIN SUBTASK ON CALENDAR_EVENT.subtask_id = SUBTASK.subtask_id
    INNER JOIN HABIT ON SUBTASK.habit_id = HABIT.habit_id
    INNER JOIN CATEGORY ON HABIT.category_id = CATEGORY.category_id
    WHERE CATEGORY.user_id = ?');
if (!$countStmt) {
    die('Calendar data is temporarily unavailable.');
}
mysqli_stmt_bind_param($countStmt, 'i', $userId);
mysqli_stmt_execute($countStmt);
mysqli_stmt_bind_result($countStmt, $totalEvents);
mysqli_stmt_fetch($countStmt);
mysqli_stmt_close($countStmt);
$totalPages = (int) ceil($totalEvents / $perPage);

if ($totalPages > 0 && $page > $totalPages) {
    $page = $totalPages;
    $offset = ($page - 1) * $perPage;
}

// Read-only page — no add/edit/delete forms anywhere here. Every row
// is a side effect of logging a subtask on the Subtasks page; this
// page just displays what already happened.
$eventStmt = mysqli_prepare($conn, 'SELECT CALENDAR_EVENT.*, SUBTASK.subtask_name, HABIT.habit_name
    FROM CALENDAR_EVENT
    INNER JOIN SUBTASK ON CALENDAR_EVENT.subtask_id = SUBTASK.subtask_id
    INNER JOIN HABIT ON SUBTASK.habit_id = HABIT.habit_id
    INNER JOIN CATEGORY ON HABIT.category_id = CATEGORY.category_id
    WHERE CATEGORY.user_id = ?
    ORDER BY CALENDAR_EVENT.event_date DESC, CALENDAR_EVENT.event_id DESC
    LIMIT ? OFFSET ?');
if (!$eventStmt) {
    die('Calendar data is temporarily unavailable.');
}
mysqli_stmt_bind_param($eventStmt, 'iii', $userId, $perPage, $offset);
mysqli_stmt_execute($eventStmt);
$eventResult = mysqli_stmt_get_result($eventStmt);
$events = mysqli_fetch_all($eventResult, MYSQLI_ASSOC);
mysqli_stmt_close($eventStmt);
